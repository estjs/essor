// ============================================================================
// Constant Evaluation
// ============================================================================

export const CANNOT_EVALUATE = Symbol('CANNOT_EVALUATE')

const evalCache = new WeakMap<t.Node, any>()

/**
 * Try to evaluate an expression at compile time.
 * Returns the constant value or CANNOT_EVALUATE symbol.
 */
export function evaluateConstant(expr: t.Expression): any {
  if (evalCache.has(expr)) {
    return evalCache.get(expr)
  }
  const result = computeConstant(expr)
  evalCache.set(expr, result)
  return result
}

function computeConstant(expr: t.Expression): any {
  // Literals
  if (t.isStringLiteral(expr)) return expr.value
  if (t.isNumericLiteral(expr)) return expr.value
  if (t.isBooleanLiteral(expr)) return expr.value
  if (t.isNullLiteral(expr)) return null
  if (t.isIdentifier(expr) && expr.name === 'undefined') return undefined

  // Unary expressions
  if (t.isUnaryExpression(expr)) {
    const arg = evaluateConstant(expr.argument)
    if (arg === CANNOT_EVALUATE) return CANNOT_EVALUATE

    switch (expr.operator) {
      case '!':
        return !arg
      case '-':
        return -arg
      case '+':
        return +arg
      case '~':
        return ~arg
      case 'void':
        return void arg
      case 'typeof':
        return typeof arg
      default:
        return CANNOT_EVALUATE
    }
  }

  // Binary and logical expressions
  if (t.isBinaryExpression(expr) || t.isLogicalExpression(expr)) {
    if (t.isPrivateName(expr.left)) return CANNOT_EVALUATE

    const left = evaluateConstant(expr.left)
    const right = evaluateConstant(expr.right)
    if (left === CANNOT_EVALUATE || right === CANNOT_EVALUATE) return CANNOT_EVALUATE

    switch (expr.operator) {
      case '+':
        return left + right
      case '-':
        return left - right
      case '*':
        return left * right
      case '/':
        return left / right
      case '%':
        return left % right
      case '==':
        // eslint-disable-next-line eqeqeq
        return left == right
      case '===':
        return left === right
      case '!=':
        // eslint-disable-next-line eqeqeq
        return left != right
      case '!==':
        return left !== right
      case '<':
        return left < right
      case '>':
        return left > right
      case '<=':
        return left <= right
      case '>=':
        return left >= right
      case '&&':
        return left && right
      case '||':
        return left || right
      default:
        return CANNOT_EVALUATE
    }
  }

  // Conditional expression
  if (t.isConditionalExpression(expr)) {
    const test = evaluateConstant(expr.test)
    if (test === CANNOT_EVALUATE) return CANNOT_EVALUATE
    return test ? evaluateConstant(expr.consequent) : evaluateConstant(expr.alternate)
  }

  // Template literals (simple cases)
  if (t.isTemplateLiteral(expr)) {
    if (expr.expressions.length === 0) {
      return expr.quasis[0].value.cooked
    }
    // Try to evaluate all expressions
    const parts: string[] = []
    for (let i = 0; i < expr.quasis.length; i++) {
      parts.push(expr.quasis[i].value.cooked ?? '')
      if (i < expr.expressions.length) {
        const exprValue = evaluateConstant(expr.expressions[i] as t.Expression)
        if (exprValue === CANNOT_EVALUATE) return CANNOT_EVALUATE
        parts.push(String(exprValue))
      }
    }
    return parts.join('')
  }

  // Array expressions
  if (t.isArrayExpression(expr)) {
    const arr: any[] = []
    for (const el of expr.elements) {
      if (!el || t.isSpreadElement(el)) return CANNOT_EVALUATE
      const value = evaluateConstant(el)
      if (value === CANNOT_EVALUATE) return CANNOT_EVALUATE
      arr.push(value)
    }
    return arr
  }

  // Object expressions
  if (t.isObjectExpression(expr)) {
    const obj: Record<string, any> = {}
    for (const prop of expr.properties) {
      if (t.isSpreadElement(prop) || t.isObjectMethod(prop)) {
        return CANNOT_EVALUATE
      }
      if (prop.computed) return CANNOT_EVALUATE

      const key = t.isIdentifier(prop.key)
        ? prop.key.name
        : t.isStringLiteral(prop.key)
          ? prop.key.value
          : t.isNumericLiteral(prop.key)
            ? String(prop.key.value)
            : null

      if (!key) return CANNOT_EVALUATE

      const value = evaluateConstant(prop.value as t.Expression)
      if (value === CANNOT_EVALUATE) return CANNOT_EVALUATE
      obj[key] = value
    }
    return obj
  }

  return CANNOT_EVALUATE
}
